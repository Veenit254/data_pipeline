"""Append gap queries (and new source websites) to config/query_plan.json: the agent's only way to edit
the plan. Append-only: it never changes or removes existing queries, phases or other settings.

  python scripts/add_queries.py --year-tag 2008 --query "compulsory delisting order 2008 site:nseindia.com" \
      --query "SEBI order delisting 2008"
  python scripts/add_queries.py --add-domain capitalmarket.com

- Queries go to the phase "agent_added" (created at the end if missing) as {"q": ..., "year_tag": ...}.
- At most 8 queries and 3 domains per call; queries 5-200 characters, printable text only; queries
  already anywhere in the plan (or generated by the historical focus) are skipped.
- Domains go to fetch_domains: a bare host name, not in deny_domains.
"""
from __future__ import annotations

import argparse
import json
import re
import sys

from common import CONFIG, emit, log

PLAN = CONFIG / "query_plan.json"
MAX_QUERIES, MAX_DOMAINS = 8, 3
YEAR_TAG_RE = re.compile(r"^(19[89]\d|20[0-4]\d|master)$")
HOST_RE = re.compile(r"^(?=.{4,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,24}$")
BAD_TEXT_RE = re.compile(r"[\x00-\x1f\x7f`$<>|;{}\\]")


def existing_queries(plan: dict) -> set[str]:
    qs = {(q["q"] if isinstance(q, dict) else q).strip().lower() for ph in plan.get("phases", []) for q in ph["queries"]}
    try:
        import historical
        qs |= {it["query"].strip().lower() for it in historical.items({})}
    except Exception:
        pass
    return qs


def add(plan: dict, queries: list[str], year_tag: str | None, domains: list[str]) -> dict:
    out = {"added_queries": [], "skipped_queries": [], "added_domains": [], "skipped_domains": []}
    if queries:
        if not year_tag or not YEAR_TAG_RE.match(year_tag):
            raise ValueError("--year-tag must be a year (e.g. 2008) or 'master'")
        seen = existing_queries(plan)
        phase = next((p for p in plan["phases"] if p["name"] == "agent_added"), None)
        if phase is None:
            phase = {"name": "agent_added", "year_tag": "per_query", "pages": 1, "queries": []}
            plan["phases"].append(phase)
        for q in queries:
            q = re.sub(r"\s+", " ", q).strip()
            why = ("too short/long" if not 5 <= len(q) <= 200 else "disallowed characters" if BAD_TEXT_RE.search(q)
                   else "already in the plan" if q.lower() in seen else None)
            if why:
                out["skipped_queries"].append({"query": q[:200], "why": why})
                continue
            phase["queries"].append({"q": q, "year_tag": year_tag})
            seen.add(q.lower())
            out["added_queries"].append(q)
    for d in domains:
        d = d.strip().lower().removeprefix("www.")
        deny = plan.get("deny_domains", [])
        why = ("not a host name" if not HOST_RE.match(d) else "denied" if any(d == x or d.endswith("." + x) for x in deny)
               else "already listed" if d in plan.get("fetch_domains", []) else None)
        if why:
            out["skipped_domains"].append({"domain": d, "why": why})
            continue
        plan.setdefault("fetch_domains", []).append(d)
        out["added_domains"].append(d)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter,
                                 allow_abbrev=False)
    ap.add_argument("--query", action="append", default=[])
    ap.add_argument("--year-tag")
    ap.add_argument("--add-domain", action="append", default=[])
    a = ap.parse_args()
    if not a.query and not a.add_domain:
        ap.error("give --query (with --year-tag) and/or --add-domain")
    if len(a.query) > MAX_QUERIES or len(a.add_domain) > MAX_DOMAINS:
        emit({"error": f"at most {MAX_QUERIES} queries and {MAX_DOMAINS} domains per call"})
        return 2
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    try:
        out = add(plan, a.query, a.year_tag, a.add_domain)
    except ValueError as e:
        emit({"error": str(e)})
        return 2
    if out["added_queries"] or out["added_domains"]:
        tmp = PLAN.with_suffix(".tmp")
        tmp.write_text(json.dumps(plan, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        tmp.replace(PLAN)
        log(f"agent added {len(out['added_queries'])} queries, {len(out['added_domains'])} domains to the plan",
            kind="agent_queries_added", **out)
    emit(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
